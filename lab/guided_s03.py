# U = 2 ln x1 + 3 ln x2, p1 = 3, p2 = 2, m = 300. Given in the notes with
# the answer worked out, so this part is a warm-up on the four moves.

def draw_tangency(ax, stage):
    _frame(ax, 165, 240, "x1", "x2")
    _budget(ax, 3, 2, 300, color=LINE, lw=2.2, zorder=4, label="budget  3x1 + 2x2 = 300")
    ax.fill_between([0, 100], [150, 0], 0, color=FILL, alpha=0.07, lw=0)
    ax.annotate(r"$m/p_2$", (0, 150), textcoords="offset points", xytext=(6, 4),
                color=LINE, fontsize=10)
    ax.annotate(r"$m/p_1$", (100, 0), textcoords="offset points", xytext=(0, 6),
                ha="center", color=LINE, fontsize=10)

    if stage >= 1:
        xs = np.array([0, 100])
        ax.plot(xs, 2.25 * xs, color=MUTE, lw=1.2, ls=":",
                label=r"tangency: $p_2x_2 = \frac{\beta}{\alpha}\,p_1x_1$")
    if stage >= 2:
        xs = np.linspace(8, 165, 300)
        level = 2 * np.log(40) + 3 * np.log(90)
        ax.plot(xs, np.exp((level - 2 * np.log(xs)) / 3), color=CURVE, lw=2, zorder=4)
        _dot(ax, 40, 90, "A", 8, 2)
    if stage >= 3:
        ax.text(0.98, 0.62, r"good 1 gets the share $\frac{\alpha}{\alpha+\beta}$ of $m$",
                transform=ax.transAxes, ha="right", color=INK, fontsize=11)
    if stage >= 4:
        _budget(ax, 3, 2, 450, color=HALF, lw=1.8, ls="--", alpha=1 if stage == 4 else 0.45,
                label="Try it (b): more income")
        _dot(ax, 60, 135, "(b)", 8, 0, colour=HALF)
    if stage >= 5:
        _budget(ax, 6, 2, 300, color=NEW, lw=1.8, ls="--", alpha=1 if stage == 5 else 0.45,
                label=r"Try it (c): a higher $p_1$")
        _dot(ax, 20, 90, "(c)", -10, 6, colour=NEW, ha="right")
    if stage >= 6:
        ax.axhline(90, color=NEW, lw=1, ls=":", xmax=0.5)
        ax.text(84, 80, r"$x_2$ unchanged", color=NEW, fontsize=10)
    _legend(ax)


