    if stage < 4:
        ps.text(0.5, 0.5, "?", transform=ps.transAxes, ha="center", va="center",
                color=MUTE, fontsize=28)
        return
    for k in (2, 4, 6):
        ps.plot([0, k], [k, 0], color=CURVE, lw=0.9, ls=":", alpha=0.6)
    _budget(ps, 10, 15, 60, color=LINE, lw=2, label=r"$p_1 < p_2$")
