# U = ln x1 + ln x2, m = 80, p1 = 1, p2 = 2, a 100% tariff on good 2.

def draw_tariff(ax, stage):
    _frame(ax, 90, 46, "x1", "x2")
    _budget(ax, 1, 2, 80, color=LINE, lw=2.2, zorder=4, label="before the tariff")
    ax.fill_between([0, 80], [40, 0], 0, color=FILL, alpha=0.06, lw=0)
    xs = np.linspace(17, 90, 300)
    if stage >= 1:
        ax.plot(xs, 800 / xs, color=CURVE, lw=1.8, zorder=4)
        ax.text(86, 800 / 86 + 1.2, r"$U_0$", color=CURVE, fontsize=11)
        _dot(ax, 40, 20, "A", 6, 6)
    if stage >= 2:
        _budget(ax, 1, 4, 80, color=NEW, lw=2, ls="--", zorder=4, label="with the tariff")
    if stage >= 3:
        xs2 = np.linspace(4.5, 90, 300)
        ax.plot(xs2, 400 / xs2, color=CURVE, lw=1.2, ls=":", zorder=4)
        _dot(ax, 40, 10, "C", 6, -14)
    if stage >= 4:
        # Down and left of C: the B arrows arrive from the upper right later.
        ax.annotate(r"revenue $= \tau\, p_2\, x_2^C$", (40, 10), textcoords="data",
                    xytext=(4, 3), color=NEW, fontsize=10,
                    arrowprops=dict(arrowstyle="-", color=NEW, lw=0.8))
    if stage >= 5:
        _budget(ax, 1, 2, 60, color=GREEN, lw=1.8, ls=":", zorder=4,
                label="lump sum, same revenue")
        xs3 = np.linspace(10.5, 90, 300)
        ax.plot(xs3, 450 / xs3, color=GREEN, lw=1, alpha=0.7)
        _dot(ax, 30, 15, "D", -10, 4, colour=GREEN, ha="right")
    if stage >= 6:
        ax.text(0.98, 0.6, "D is on a higher curve than C:\nthe gap is the deadweight loss",
                transform=ax.transAxes, ha="right", color=GREEN, fontsize=9.5)
    if stage >= 7:
        bx, by = 800 ** 0.5 * 2, 800 ** 0.5 / 2          # cheapest bundle on U0 at (1, 4)
        ax.plot([0, by * 4 + bx], [by + bx / 4, 0], color=GREY, lw=1.2, ls="--",
                label="new prices, old utility")
        _dot(ax, bx, by, "B", 8, 2, colour=INK)
        ax.annotate("", xy=(bx, by), xytext=(40, 20),
                    arrowprops=dict(arrowstyle="-|>", color=INK, lw=1.4,
                                    shrinkA=6, shrinkB=6))
        ax.text((40 + bx) / 2 + 1, (20 + by) / 2 + 1.5, "substitution", color=INK,
                fontsize=9)
    if stage >= 8:
        ax.annotate("", xy=(40, 10), xytext=(bx, by),
                    arrowprops=dict(arrowstyle="-|>", color=INK, lw=1.4,
                                    shrinkA=6, shrinkB=6))
        ax.text((40 + bx) / 2 + 2, (10 + by) / 2 - 3, "income", color=INK, fontsize=9)
    _legend(ax)


