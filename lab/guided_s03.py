DEMAND_PTS = [(15, 4), (20, 3), (30, 2)]


def draw_demand(fig, stage):
    ax, ex = fig.subplots(1, 2)
    _frame(ax, 36, 7.5, "x1", "p1")
    ax.set_title("Demand curve", loc="left", color=INK, fontsize=10)
    _dot(ax, 10, 6, "(10, 6) given", 8, 2, colour=LINE)
    if stage >= 1:
        ax.text(0.97, 0.92, r"$x_1^* = \frac{m}{2p_1}$", transform=ax.transAxes,
                ha="right", color=INK, fontsize=12)
    for i, (x, p) in enumerate(DEMAND_PTS):
        if stage >= i + 2:
            _dot(ax, x, p, "(%d, %d)" % (x, p), 6, 4)
    if stage >= 4:
        xs = np.linspace(8.2, 36, 200)
        ax.plot(xs, 60 / xs, color=CURVE, lw=1.8, zorder=3)
    if stage >= 5:
        for x, p in ((10, 6), (30, 2)):
            ax.fill_between([0, x], 0, p, color=CURVE, alpha=0.08, lw=0)
        ax.text(0.97, 0.55, r"$p_1 x_1$ the same everywhere", transform=ax.transAxes,
                ha="right", color=CURVE, fontsize=9.5)

    _frame(ex, 70, 260, "x1", "income m")
    ex.set_title("Engel curve", loc="left", color=INK, fontsize=10)
    if stage < 6:
        ex.text(0.5, 0.5, "?", transform=ex.transAxes, ha="center", va="center",
                color=MUTE, fontsize=28)
        return
    ms = np.linspace(0, 250, 50)
    ex.plot(ms / 4, ms, color=CURVE, lw=2, label="Cobb-Douglas: a straight ray")
    _dot(ex, 30, 120, "", colour=CURVE)
    _dot(ex, 60, 240, "", colour=CURVE)
    ex.annotate("", xy=(60, 240), xytext=(30, 120),
                arrowprops=dict(arrowstyle="->", color=MUTE, lw=1))
    if stage >= 7:
        mm = np.linspace(60, 250, 100)
        ex.plot(25 * (mm / 120) ** -0.5, mm, color=NEW, lw=1.6, ls="--",
                label=r"inferior, $\eta < 0$")
    if stage >= 8:
        mm = np.linspace(20, 250, 100)
        ex.plot(30 * (mm / 120) ** 1.6, mm, color=HALF, lw=1.6, ls="--",
                label=r"luxury, $\eta > 1$")
    _legend(ex, loc="lower right")
    fig.subplots_adjust(wspace=0.25)


